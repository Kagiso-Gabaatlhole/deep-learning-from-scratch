RESULTS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "results")


def _ensure_results_dir():
    os.makedirs(RESULTS_DIR, exist_ok=True)


def _mlp_train(epochs: int = 20, seed: int = 0, verbose: bool = True):
    from sklearn.datasets import load_digits
    from sklearn.model_selection import train_test_split

    data = load_digits()
    X = data.data.astype(np.float64) / 16.0
    y = data.target.astype(int)
    Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, random_state=seed, stratify=y)

    rng = np.random.default_rng(seed)
    model = Sequential(
        [Dense(64, 128, rng=rng), ReLU(), Dense(128, 10, rng=rng, init="glorot")],
        seed=seed,
    )
    opt = Adam(lr=1e-3)
    history = model.fit(Xtr, ytr, epochs=epochs, batch_size=64, optimizer=opt, verbose=verbose)
    pred = model.predict(Xte)
    acc = float(np.mean(pred == yte))
    return {
        "model": "mlp",
        "epochs": epochs,
        "train_samples": int(Xtr.shape[0]),
        "test_samples": int(Xte.shape[0]),
        "final_train_loss": float(history["loss"][-1]),
        "test_accuracy": acc,
    }


def _cnn_train(epochs: int = 8, seed: int = 0, verbose: bool = True):
    from sklearn.datasets import load_digits
    from sklearn.model_selection import train_test_split

    data = load_digits()
    X = (data.images.astype(np.float64) / 16.0)[:, None, :, :]  # (N,1,8,8)
    y = data.target.astype(int)
    Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, random_state=seed, stratify=y)

    rng = np.random.default_rng(seed)
    model = Sequential(
        [
            Conv2D(1, 8, 3, rng=rng, padding=1),
            # manual relu via layer
            _ReLU4D(),
            MaxPool2D(2),
            Flatten(),
            Dense(8 * 4 * 4, 32, rng=rng),
            ReLU(),
            Dense(32, 10, rng=rng, init="glorot"),
        ],
        seed=seed,
    )
    opt = Adam(lr=1e-3)
    history = model.fit(Xtr, ytr, epochs=epochs, batch_size=64, optimizer=opt, verbose=verbose)
    pred = model.predict(Xte)
    acc = float(np.mean(pred == yte))
    return {
        "model": "cnn",
        "epochs": epochs,
        "train_samples": int(Xtr.shape[0]),
        "test_samples": int(Xte.shape[0]),
        "final_train_loss": float(history["loss"][-1]),
        "test_accuracy": acc,
    }


class _ReLU4D:
    """ReLU that works on (N,C,H,W) by reshaping not needed (elementwise)."""
    name = "relu"

    def __init__(self):
        self._layer = ReLU()

    def forward(self, x):
        # ReLU is elementwise; reuse but cache shape automatically
        return self._layer.forward(x)

    def backward(self, dy):
        return self._layer.backward(dy)

    def params(self):
        return {}

    def grads(self):
        return {}


def _lstm_train(epochs: int = 20, seed: int = 0, verbose: bool = True):
    # Synthetic sequence task: parity of a binary sequence (sum mod 2).
    rng = np.random.default_rng(seed)
    n = 400
    T = 8
    X = rng.integers(0, 2, size=(n, T, 1)).astype(np.float64)
    y = (X.sum(axis=1)[:, 0] % 2).astype(int)
    split = int(0.8 * n)
    Xtr, Xte = X[:split], X[split:]
    ytr, yte = y[:split], y[split:]

    rng2 = np.random.default_rng(seed + 1)
    model = Sequential(
        [LSTM(1, 32, rng=rng2, return_sequences=False), Dense(32, 2, rng=rng2, init="glorot")],
        seed=seed,
    )
    opt = Adam(lr=5e-2)
    history = model.fit(Xtr, ytr, epochs=epochs, batch_size=32, optimizer=opt, verbose=verbose)
    pred = model.predict(Xte)
    acc = float(np.mean(pred == yte))
    # chance level for binary ~0.5
    return {
        "model": "lstm",
        "task": "parity of binary sequence (length 8)",
        "epochs": epochs,
        "train_samples": int(Xtr.shape[0]),
        "test_samples": int(Xte.shape[0]),
        "final_train_loss": float(history["loss"][-1]),
        "test_accuracy": acc,
        "loss_first": float(history["loss"][0]),
        "loss_last": float(history["loss"][-1]),
    }


def _write_result(res: dict[str, Any]) -> str:
    _ensure_results_dir()
    name = res["model"]
    path = os.path.join(RESULTS_DIR, f"{name}.md")
    lines = [f"# {name.upper()} training result", "", "Auto-generated by `python -m dlfs train`.", "", "## Config"]
    for k, v in res.items():
        lines.append(f"- {k}: {v}")
    lines.append("")
    lines.append("## Notes")
    lines.append("- Teaching-scale run on CPU with pure NumPy.")
    lines.append("- Numbers are observed from an actual run, not invented.")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return path


def train_command(args):
    model = args.model
    epochs = args.epochs
    seed = getattr(args, "seed", 0)
    if model == "mlp":
        res = _mlp_train(epochs=epochs, seed=seed)
    elif model == "cnn":
        res = _cnn_train(epochs=epochs, seed=seed)
    elif model == "lstm":
        res = _lstm_train(epochs=epochs, seed=seed)
    else:
        raise ValueError(model)
    path = _write_result(res)
    print(f"results written to {path}")
    print(f"test_accuracy={res['test_accuracy']:.4f}")
    if model == "lstm":
        print(f"loss {res['loss_first']:.4f} -> {res['loss_last']:.4f}")
    return 0


def check_command(args):
    layer = args.layer
    res = check_layer(layer)
    print(f"layer={res.layer} max_rel_error={res.max_rel_error:.3e} passed={res.passed}")
    print("details:", res.details)
    return 0 if res.passed else 1


def list_command(args):
    print("models: mlp, cnn, lstm")
    print("layers: dense, conv, lstm (also relu, sigmoid, tanh, softmax, maxpool)")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(prog="dlfs")
    sub = parser.add_subparsers(dest="command", required=True)
    p_train = sub.add_parser("train")
    p_train.add_argument("--model", choices=["mlp", "cnn", "lstm"], required=True)
    p_train.add_argument("--epochs", type=int, default=None)
    p_train.add_argument("--seed", type=int, default=0)
    p_train.set_defaults(func=train_command)
    p_check = sub.add_parser("check")
    p_check.add_argument("--layer", choices=["dense", "conv", "lstm"], required=True)
    p_check.set_defaults(func=check_command)
    p_list = sub.add_parser("list")
    p_list.set_defaults(func=list_command)

    args = parser.parse_args(argv)
    if args.command == "train" and args.epochs is None:
        defaults = {"mlp": 20, "cnn": 8, "lstm": 50}
        args.epochs = defaults[args.model]
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())